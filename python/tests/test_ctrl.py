class TestConfigStatusResp:
    def setup_method(self):
        self.frm = CtrlFrame("h3c")
        self.msg = decode_wire(self.frm, bytes.fromhex(CFG_RESP))

    def test_header(self):
        assert self.msg.msg_type == 6
        assert self.msg.seq == 286

    def test_contains_wlan_config(self):
        assert self.msg.one(0xFDE8) is not None
        wlan = self.msg.one(0xFDE8)
        # Header [7 x u32] + two band records; 2.4G SSID-1 embedded.
        assert wlan.startswith(bytes.fromhex(
            "00000001 00000001 00000006 00000000 00000001 00000000 00000000"
            .replace(" ", "")))
        assert b"SSID-1" in wlan
        assert b"5G-SSID-1" in wlan

    def test_find_multi_value(self):
        assert len(self.msg.find(32)) == 2  # Radio Operational State x2
        assert len(self.msg.find(31)) == 2  # Radio Administrative State x2
